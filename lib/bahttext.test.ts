import assert from "node:assert/strict";
import { test } from "node:test";
import { bahtText } from "./bahttext.ts";

test("bahtText", () => {
  const cases: [number, string][] = [
    [0, "ศูนย์บาทถ้วน"],
    [1, "หนึ่งบาทถ้วน"],
    [10, "สิบบาทถ้วน"],
    [11, "สิบเอ็ดบาทถ้วน"],
    [21, "ยี่สิบเอ็ดบาทถ้วน"],
    [101, "หนึ่งร้อยเอ็ดบาทถ้วน"],
    [1250.5, "หนึ่งพันสองร้อยห้าสิบบาทห้าสิบสตางค์"],
    [0.25, "ยี่สิบห้าสตางค์"],
    [0.01, "หนึ่งสตางค์"],
    [208854, "สองแสนแปดพันแปดร้อยห้าสิบสี่บาทถ้วน"],
    [1_000_000, "หนึ่งล้านบาทถ้วน"],
    [1_000_001, "หนึ่งล้านเอ็ดบาทถ้วน"],
    [21_000_000, "ยี่สิบเอ็ดล้านบาทถ้วน"],
    [2_500_000.75, "สองล้านห้าแสนบาทเจ็ดสิบห้าสตางค์"],
    [53_500.1, "ห้าหมื่นสามพันห้าร้อยบาทสิบสตางค์"],
  ];
  for (const [amount, words] of cases) assert.equal(bahtText(amount), words, String(amount));
});
